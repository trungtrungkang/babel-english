export const seedLesson = seedLessons[0];
export function initialState() {
 return { schemaVersion: 2, lang: 'vi', lesson: structuredClone(seedLesson), draft: null, attempt: null, submission: null, feedback: null, walkthrough: false, records: {} };
}
const fields = ['lesson', 'draft', 'attempt', 'submission', 'feedback'];
export function snapshotCurrent(state) {
 const records = { ...state.records };
 records[state.lesson.id] = Object.fromEntries(fields.map(key => [key, structuredClone(state[key] ?? null)]));
 return { ...state, schemaVersion: 2, records };
}
export function selectLesson(state, id) {
 const seed = seedLessons.find(item => item.id === id);
 if (!seed) throw new Error('unknown-lesson');
 const saved = snapshotCurrent(state);
 const record = saved.records[id] || { lesson: structuredClone(seed), draft: null, attempt: null, submission: null, feedback: null };
 return { ...saved, ...structuredClone(record) };
}
export function lessonRecord(state, id) {
 if (state.lesson.id === id) return state;
 return state.records?.[id] || { lesson: seedLessons.find(item => item.id === id), attempt: null, submission: null, feedback: null };
}
export function migrateState(value) {
 if (!value || ![1,2].includes(value.schemaVersion) || !value.lesson || validateLesson(value.lesson)) return initialState();
 const seed = seedLessons.find(item => item.id === value.lesson.id);
 if (!seed) return initialState();
 const enrich = record => {
  const base = seedLessons.find(item => item.id === record.lesson?.id);
  if (!base || validateLesson(record.lesson)) return null;
  const result = { ...record, lesson: { ...structuredClone(base), ...record.lesson } };
  for (const key of ['attempt','submission']) if (result[key]?.lesson) result[key] = { ...result[key], lesson: { ...structuredClone(base), ...result[key].lesson } };
  return result;
 };
 const records = Object.fromEntries(Object.entries(value.records || {}).map(([id,record]) => [id,enrich(record)]).filter(([,record])=>record));
 return { ...initialState(), ...enrich(value), records, schemaVersion: 2, lang: value.lang === 'en' ? 'en' : 'vi' };
}
export function practiceSentence(lesson, choice) {
 const selected = lesson.practice.choices.includes(choice) ? choice : lesson.practice.choices[0];
 return lesson.practice.template.replace('{choice}', selected);
}
export function newAttempt(lesson) {
  return { lessonId: lesson.id, lessonVersion: lesson.version, lesson: structuredClone(lesson), step: 0, startedAt: new Date().toISOString(), completedSteps: [], hintUsed: false };
}
export function advanceAttempt(attempt) {
  return { ...attempt, completedSteps: [...new Set([...attempt.completedSteps, steps[attempt.step]])], step: Math.min(5, attempt.step + 1) };
}
export function createSubmission(attempt, recording, now = new Date().toISOString()) {
  if (!recording?.size || !recording?.id) throw new Error('recording-required');
  if (attempt.step !== 5) throw new Error('assessment-required');
  return { id: `submission-${Date.now()}`, lessonId: attempt.lessonId, lessonVersion: attempt.lessonVersion, lesson: structuredClone(attempt.lesson), recordingId: recording.id, duration: recording.duration, submittedAt: now, completion: 'submitted', mastery: 'pending', hintUsed: attempt.hintUsed, practiceEvidence: structuredClone(attempt.task || null) };
}
export function validateLesson(lesson) {
  if (!lesson.title?.trim() || lesson.title.length > 120) return 'title';
  if (!lesson.objective?.vi?.trim() || !lesson.objective?.en?.trim()) return 'objective';
  if (!Array.isArray(lesson.lines) || lesson.lines.length < 2 || lesson.lines.length > 8 || lesson.lines.some(x => typeof x !== 'string' || !x.trim() || x.length > 250)) return 'lines';
  if (!lesson.prompt?.trim() || lesson.prompt.length > 250) return 'prompt';
  if (lesson.videoUrl) {
    try { if (new URL(lesson.videoUrl).protocol !== 'https:') return 'video'; } catch { return 'video'; }
  }
  return null;
}
export function completionPercent(state) {
  if (state.submission) return 100;
  return state.attempt ? Math.round(state.attempt.completedSteps.length / 6 * 100) : 0;
}

